"""## 第一題：製作自己的廣告成效報表"""

# 讀取完整學號並進行格式化處理
student_id = input("請輸入完整學號：").strip().upper()

# 提取末三碼及各別數字
tail = student_id[-3:]
a = int(student_id[-3])
b = int(student_id[-2])
c = int(student_id[-1])
s = a + b + c

# 驗證輸出結果
print(f"\n學號 (student_id): {student_id}")
print(f"末三碼 (tail): {tail}")
print(f"a = {a}, b = {b}, c = {c}")
print(f"s (a + b + c) = {s}")
def ad_report(impressions, clicks, target=3.0):
    # 曝光次數為 0 時，回傳 (None, False)
    if impressions == 0:
        return (None, False)

    # 計算 CTR 百分比
    ctr = (clicks / impressions) * 100

    # 判斷是否達標
    passed = ctr >= target
    return (ctr, passed)

# 產生符合學號變數的廣告數據
ads = [
    ("搜尋廣告", 1000 + 100 * a, 30 + 5 * b),
    ("社群廣告", 1200 + 100 * b, 24 + 4 * c),
    ("影音廣告", 0, 0),
]

# 個人 CTR 門檻
target = 2.5 + 0.1 * c

# 逐筆計算並印出報表
print(f"學號：{student_id}")
print(f"CTR門檻：{target:.2f}%")

passed_count = 0
for name, imp, clk in ads:
    ctr, passed = ad_report(imp, clk, target=target)

    # 格式化 CTR 顯示
    if ctr is None:
        ctr_display = "無曝光資料"
    else:
        ctr_display = f"{ctr:.2f}%"

    if passed:
        passed_count += 1

    print(f"{name}：曝光={imp}，點擊={clk}，CTR={ctr_display}，達標={passed}")

print(f"達標廣告數：{passed_count}")

# 驗證預設門檻與零點擊測試
default_test = ad_report(1000, 30)
zero_click_test = ad_report(1000, 0)

print(f"預設門檻測試：{default_test}")
print(f"零點擊測試：{zero_click_test}")

