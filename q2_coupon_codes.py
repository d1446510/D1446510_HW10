# 讀取完整學號並進行格式化處理
student_id = input("請輸入完整學號：").strip().upper()

# 提取末三碼及各別數字
tail = student_id[-3:]
a = int(student_id[-3])
b = int(student_id[-2])
c = int(student_id[-1])
s = a + b + c

# 驗證輸出結果
print(f"\n學號 (student_id): {student_id}")
print(f"末三碼 (tail): {tail}")
print(f"a = {a}, b = {b}, c = {c}")
print(f"s (a + b + c) = {s}")
def collect_codes(raw_codes, saved=None):
    # 每次回傳新的串列，若未傳入 saved，從新的空串列開始，不修改原本傳入的 saved 串列
    result = list(saved) if saved is not None else []

    for raw_code in raw_codes:
        cleaned = raw_code.strip().upper()
        # 略過空字串
        if cleaned == "":
            continue
        # 相同優惠碼只保留一次，順序以首次出現為準
        if cleaned not in result:
            result.append(cleaned)

    return result

# 建立資料
saved = ["BASE"]
raw_a = [" welcome" + tail + " ", "vip" + tail, "", "WELCOME" + tail, "   "]
raw_b = [" new" + tail + " ", " welcome" + tail + " "]

# 複製一份原始 raw_a 和 saved 來比對是否被函式內部的運算修改
raw_a_orig = list(raw_a)
saved_orig = list(saved)

# 呼叫與計算
activity_a = collect_codes(raw_a, saved=saved)
activity_b = collect_codes(raw_b)
empty_test = collect_codes([])

# 輸出結果
print(f"學號：{student_id}")
print(f"活動A：{activity_a}")
print(f"活動B：{activity_b}")
print(f"原始saved：{saved_orig}")
print(f"原始raw_a：{raw_a_orig}")
print(f"空資料：{empty_test}")